/*
 * 实时会话编排任务（方案 C 的"主体"）。
 *
 * 这个模块把之前分散在**网关**上的编排逻辑全部接了过来：
 *
 *     等 WiFi → 等时间 → 读 key → TLS → WS → 会话
 *       → 半双工闸门 / 音频泵 / 情绪引擎 / 安全改舵 / 界面投递 / 断线重连
 *
 * 任务模型
 * =======
 *   本任务（sc_rt_task）：**唯一**碰网络与 StepFun 会话的任务。
 *                          同时负责推进心情状态机（离线时也在跑，
 *                          所以"闲置会睡着"在断网时照样生效）。
 *   采集任务：采到 16k PCM → **先问 sc_rt_uplink_open()** → 开放才入队。
 *   播放任务：从下行队列取 → 喇叭（本任务负责往队列里放）。
 *   UI 任务：LVGL 独占（本模块只通过 sc_face_post_* 投递）。
 *
 * 半双工闸门为什么必须在**入队前**判
 * =================================
 * 板子的喇叭和麦克风相距几厘米，没有 AEC。全双工的话机器人会被自己的
 * 声音触发 VAD，然后**自己打断自己** —— 表现是"说半句就停、停完又从头说"。
 *
 * 闸门如果放在"发送前"判，采集到的音频还是先进了环形队列，
 * 等闸门打开时会把**几秒前的旧声音**发上去 —— 模型听到的是错位的对话，
 * 表现为"答非所问"，比丢一点音频糟糕得多。
 * 所以在入队前就丢掉。
 *
 * 闸门判据
 * =======
 *   "模型正在生成"  **或**  "播放队列里还有数据"  **或**  "队列刚清空不超过 500ms"
 *
 * ⚠️ 不能只看 `response.done`（第一版就是这么写的）：开机问候、安全改舵、
 * 手动点播这三条路径都不经过"VAD → response 生命周期"，于是它们在
 * 播放期间**完全不闸断** —— 问候播到一半，孩子一开口就把问候打断了。
 * 加一条"播放队列非空"就把这三条路径全兜住了。
 */

#ifndef __SUPERCHILD_SC_RT_H
#define __SUPERCHILD_SC_RT_H

#include <stdbool.h>
#include <stdint.h>

enum sc_rt_state {
    SC_RT_OFFLINE = 0,     /* 没连上（等 WiFi / 等时间 / 重连中） */
    SC_RT_CONNECTING,      /* 正在建立连接 */
    SC_RT_READY,           /* 会话可用 */
};

/* 初始化（读配置、初始化子系统）。由 main 在起任务前调用一次。 */
int  sc_rt_init(void);

/*
 * 会话任务主体。**永不返回**，用 pthread_create 起一个独立任务。
 */
void *sc_rt_task(void *arg);

/*
 * 上行闸门。采集任务在**入队前**调用。
 * @return 1 可以发送；0 应丢弃（正在播/刚播完）
 */
int  sc_rt_uplink_open(void);

/* 当前状态（供界面/日志） */
int  sc_rt_state(void);

/* 是否已连上 StepFun */
int  sc_rt_connected(void);

/*
 * 请求说一句问候（按键、或控制台触发）。
 * 线程安全，内部只置一个标志。
 */
void sc_rt_request_greet(void);

#endif /* __SUPERCHILD_SC_RT_H */
